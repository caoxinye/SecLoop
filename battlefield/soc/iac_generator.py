"""IaC generator: render the 2-VM BATTLE-FIELD lab (``docs/INTERFACES.md`` §1).

Paper Section II-C says the BATTLE-FIELD "can automatically clone a complete
experimental environment before each evaluation task begins".  This module
renders that environment as a Vagrantfile for the single shipped preset
(``sqli``), so a fresh clone or an extra VM pair can be described by one command
instead of by hand.

What this module deliberately does **not** do
--------------------------------------------
It does not create, start or provision anything, and **``soc_server.py`` never
calls it**.  A round must not generate a Vagrantfile and then drive a different,
pre-existing set of VMs: the generated environment would never be ``vagrant up``-ed, and
the manifest would describe a lab that does not exist.  Rendering IaC is
an operator action with an explicit, documented continuation::

    python -m battlefield.soc.iac_generator --attack-mode sqli
    cd <repo>/vagrant/envs/env_sqli
    vagrant up --provider vmware_desktop
    bash <repo>/vagrant/snapshots.sh         # creates kali_init / target_init
    SOAR_VAGRANT_ROOT=<repo>/vagrant/envs/env_sqli python battlefield/soc_server.py

Until ``vagrant up`` has run, ``soc_server.py`` cannot drive the environment and
says so (``vagrant_driver`` fails loudly on a missing ``Vagrantfile`` or a
missing initial snapshot).
"""

from __future__ import annotations

import argparse
import logging
import os
import sys
from pathlib import Path
from typing import Any, Mapping

logger = logging.getLogger(__name__)

__all__ = ["ENV_PRESETS", "IaCGenerator", "VAGRANTFILE_TEMPLATE", "main"]

#: ``<repo>/SecLoop/battlefield/soc/iac_generator.py`` -> ``<repo>/SecLoop``
REPO_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_OUTPUT_DIR = REPO_ROOT / "vagrant" / "envs"

VAGRANTFILE_TEMPLATE = '''# -*- mode: ruby -*-
# vi: set ft=ruby :
#
# ---------------------------------------------------------------------------
# SecLoop BATTLE-FIELD lab -- generated by battlefield/soc/iac_generator.py
# preset: {attack_mode}
#
# THIS FILE ONLY DESCRIBES THE ENVIRONMENT.  Rendering it does not create,
# start, or provision any VM.  The intended continuation is:
#
#   cd {env_dir}
#   vagrant up --provider vmware_desktop
#   bash {repo_root}/vagrant/snapshots.sh        # kali_init / target_init
#
# and only then can battlefield/soc_server.py drive this pair.  soc_server.py
# never runs `vagrant up` for you.
#
# Source files are uploaded with explicit `file` provisioners (Vagrant's
# documented "upload to a temporary location, move it with the shell
# provisioner" pattern) instead of a shared folder, so the same file works on a
# Windows host with the vmware_desktop provider and no guest tools at all.
# ---------------------------------------------------------------------------

Vagrant.configure("2") do |config|
  # No implicit /vagrant share: the lab ships its own files explicitly below.
  config.vm.synced_folder ".", "/vagrant", disabled: true

  config.vm.define "{red_name}" do |red|
    red.vm.box = "{red_box}"
    red.vm.hostname = "{red_name}"
    red.vm.network "private_network", ip: "{red_ip}"
{red_provisioners}
    red.vm.provider "vmware_desktop" do |v|
      v.memory = {red_memory}
      v.cpus = {red_cpus}
      v.gui = false
    end
    red.vm.provision "shell", path: "{red_setup}"
  end

  config.vm.define "{blue_name}" do |blue|
    blue.vm.box = "{blue_box}"
    blue.vm.hostname = "{blue_name}"
    blue.vm.network "private_network", ip: "{blue_ip}"
{blue_provisioners}
    blue.vm.provider "vmware_desktop" do |v|
      v.memory = {blue_memory}
      v.cpus = {blue_cpus}
      v.gui = false
    end
    blue.vm.provision "shell", path: "{blue_setup}"
  end
end
'''

#: ``docs/INTERFACES.md`` §1 is the source of truth for every value below.
ENV_PRESETS: dict[str, dict[str, Any]] = {
    "sqli": {
        "red": {
            "name": "kali",
            "box": "kalilinux/rolling",
            "ip": "192.168.57.199",
            "memory": 2048,
            "cpus": 2,
            "files": (("battlefield/attacks/sqli_lab.py", "/tmp/secloop/sqli_lab.py"),),
            "dirs": (),
            "setup": "vagrant/provision/attacker_setup.sh",
        },
        "blue": {
            "name": "target",
            "box": "bento/ubuntu-18.04",
            "ip": "192.168.57.200",
            "memory": 4096,
            "cpus": 2,
            "files": (),
            "dirs": (
                ("target/webapp", "/tmp/secloop/webapp"),
                ("target/suricata", "/tmp/secloop/suricata"),
            ),
            "setup": "vagrant/provision/target_setup.sh",
        },
    },
}


class IaCGenerator:
    """Renders Vagrantfiles for the shipped BATTLE-FIELD preset.

    Args:
        repo_root: repository root that the generated file references; defaults
            to the checkout this module lives in.
        output_dir: parent directory of the generated ``env_<preset>`` folders;
            defaults to ``<repo>/vagrant/envs``.
    """

    def __init__(
        self,
        repo_root: str | os.PathLike[str] | None = None,
        output_dir: str | os.PathLike[str] | None = None,
    ) -> None:
        self.repo_root = Path(repo_root).expanduser().resolve() if repo_root else REPO_ROOT
        self.output_dir = (
            Path(output_dir).expanduser().resolve() if output_dir else self.repo_root / "vagrant" / "envs"
        )

    # ------------------------------------------------------------- presets

    @staticmethod
    def list_presets() -> list[str]:
        """Shipped presets.  Only ``sqli`` ships."""
        return sorted(ENV_PRESETS)

    def preset(self, attack_mode: str = "sqli") -> dict[str, Any]:
        """Return a preset, failing loudly on an unknown attack mode."""
        if attack_mode not in ENV_PRESETS:
            raise KeyError(
                f"unknown attack mode {attack_mode!r}; shipped presets: "
                f"{', '.join(self.list_presets())}"
            )
        return ENV_PRESETS[attack_mode]

    # -------------------------------------------------------------- render

    def render(
        self, attack_mode: str = "sqli", overrides: Mapping[str, Any] | None = None
    ) -> str:
        """Render the Vagrantfile text for ``attack_mode``.

        Args:
            attack_mode: preset name (only ``sqli`` ships).
            overrides: optional ``{"red": {...}, "blue": {...}}`` field overrides
                (e.g. another IP pair for a second parallel environment).

        Raises:
            RuntimeError: a referenced source file/script is missing, or the
                rendered text fails the structural self-check.
        """
        preset = self.preset(attack_mode)
        red = dict(preset["red"])
        blue = dict(preset["blue"])
        for key, target in (("red", red), ("blue", blue)):
            if overrides and isinstance(overrides.get(key), Mapping):
                target.update(overrides[key])

        self._require_sources(red, blue)

        env_dir = self.env_dir(attack_mode)
        rendered = VAGRANTFILE_TEMPLATE.format(
            attack_mode=attack_mode,
            repo_root=self.repo_root.as_posix(),
            env_dir=env_dir.as_posix(),
            red_name=red["name"],
            red_box=red["box"],
            red_ip=red["ip"],
            red_memory=red["memory"],
            red_cpus=red["cpus"],
            red_provisioners=self._provisioner_lines(red, "red"),
            red_setup=(self.repo_root / red["setup"]).as_posix(),
            blue_name=blue["name"],
            blue_box=blue["box"],
            blue_ip=blue["ip"],
            blue_memory=blue["memory"],
            blue_cpus=blue["cpus"],
            blue_provisioners=self._provisioner_lines(blue, "blue"),
            blue_setup=(self.repo_root / blue["setup"]).as_posix(),
        )
        self._validate_render(rendered, red, blue)
        return rendered

    def env_dir(self, attack_mode: str = "sqli") -> Path:
        """Directory a generated environment lives in."""
        return self.output_dir / f"env_{attack_mode}"

    # ------------------------------------------------------------ generate

    def generate(
        self,
        attack_mode: str = "sqli",
        overrides: Mapping[str, Any] | None = None,
        *,
        force: bool = False,
    ) -> Path:
        """Write ``Vagrantfile`` + ``README.md`` for ``attack_mode``.

        Returns:
            Path of the generated Vagrantfile.

        Raises:
            FileExistsError: the target Vagrantfile exists and ``force`` is False.
            RuntimeError: see :meth:`render`.
        """
        rendered = self.render(attack_mode, overrides)
        env_dir = self.env_dir(attack_mode)
        target = env_dir / "Vagrantfile"
        if target.exists() and not force:
            raise FileExistsError(
                f"{target} already exists; pass force=True (CLI: --force) to overwrite it"
            )
        env_dir.mkdir(parents=True, exist_ok=True)
        target.write_text(rendered, encoding="utf-8", newline="\n")
        (env_dir / "README.md").write_text(
            self.usage_notes(attack_mode, target), encoding="utf-8", newline="\n"
        )
        logger.info("generated %s (%d bytes)", target, len(rendered))
        return target

    def usage_notes(self, attack_mode: str, vagrantfile: Path) -> str:
        """Markdown placed next to the generated Vagrantfile."""
        env_dir = vagrantfile.parent
        red = self.preset(attack_mode)["red"]
        blue = self.preset(attack_mode)["blue"]
        return f"""# Generated BATTLE-FIELD environment (`{attack_mode}`)

Created by `battlefield/soc/iac_generator.py`. **This directory is generated
output, not an installed environment** -- nothing has been created, started or
provisioned yet.

Machines: `{red['name']}` ({red['box']}, {red['ip']}) + `{blue['name']}`
({blue['box']}, {blue['ip']}), provider `vmware_desktop`.

## 1. Bring it up (required)

```sh
cd {env_dir.as_posix()}
vagrant up --provider vmware_desktop
```

Provisioning is real: `{red['name']}` gets Python 3 + `requests` and the attack
script; `{blue['name']}` gets Apache + PHP 7.2 + MySQL + the deliberately
vulnerable web app + Suricata with the repository's rules. Expect several
minutes and ~2 GB of box downloads on the first run.

## 2. Create the initial snapshots (required)

```sh
bash {self.repo_root.as_posix()}/vagrant/snapshots.sh {red['name']} {blue['name']}
```

The SOC restores `{blue['name']}_init` after every round; without it a round
fails loudly instead of measuring a dirty VM.

## 3. Point the SOC at this environment

```sh
SOAR_VAGRANT_ROOT={env_dir.as_posix()} \\
python {self.repo_root.as_posix()}/battlefield/soc_server.py
```

`soc_server.py` never runs `vagrant up` for you: an environment that was only
*generated* stays an empty directory, and the SOC reports that instead of
silently evaluating nothing.
"""

    # ------------------------------------------------------------- helpers

    def _provisioner_lines(self, vm: Mapping[str, Any], block_var: str) -> str:
        """Render the ``file`` provisioners for one VM.

        ``block_var`` must be the Ruby block variable used by the template
        (``red``/``blue``); using the VM *name* produces an
        ``undefined local variable`` Vagrantfile that ``vagrant validate`` rejects.
        """
        lines: list[str] = []
        for kind in ("files", "dirs"):
            for relative, destination in vm.get(kind, ()):  # type: ignore[union-attr]
                lines.append(
                    f'    {block_var}.vm.provision "file", '
                    f'source: "{(self.repo_root / relative).as_posix()}", '
                    f'destination: "{destination}"'
                )
        return "\n".join(lines)

    def _require_sources(self, red: Mapping[str, Any], blue: Mapping[str, Any]) -> None:
        missing: list[str] = []
        for vm in (red, blue):
            for relative, _ in list(vm.get("files", ())) + list(vm.get("dirs", ())):
                if not (self.repo_root / relative).exists():
                    missing.append(relative)
            setup = self.repo_root / str(vm["setup"])
            if not setup.is_file():
                missing.append(str(vm["setup"]))
        if missing:
            raise RuntimeError(
                "cannot generate a runnable environment; missing: "
                + ", ".join(sorted(missing))
                + f" (repo root: {self.repo_root})"
            )

    @staticmethod
    def _validate_render(rendered: str, red: Mapping[str, Any], blue: Mapping[str, Any]) -> None:
        """Structural self-check: two machines, right boxes/IPs/provider/memory."""
        required = [
            f'config.vm.define "{red["name"]}"',
            f'config.vm.define "{blue["name"]}"',
            f'red.vm.box = "{red["box"]}"',
            f'blue.vm.box = "{blue["box"]}"',
            f'ip: "{red["ip"]}"',
            f'ip: "{blue["ip"]}"',
            'red.vm.provider "vmware_desktop"',
            'blue.vm.provider "vmware_desktop"',
            f'v.memory = {red["memory"]}',
            f'v.memory = {blue["memory"]}',
            'red.vm.provision "shell"',
            'blue.vm.provision "shell"',
        ]
        missing = [token for token in required if token not in rendered]
        if missing:
            raise RuntimeError(
                "generated Vagrantfile failed its self-check; missing: " + ", ".join(missing)
            )
        if rendered.count("config.vm.define") != 2:
            raise RuntimeError(
                "generated Vagrantfile must define exactly 2 machines, found "
                f"{rendered.count('config.vm.define')}"
            )
        # Every `vm.provision` must hang off the Ruby block variable, never off a
        # machine name, otherwise Vagrant aborts with `undefined local variable`
        # (caught by `vagrant validate`).
        block_vars = {"red", "blue"}
        for line in rendered.splitlines():
            stripped = line.strip()
            if ".vm.provision" not in stripped:
                continue
            receiver = stripped.split(".vm.provision", 1)[0].strip()
            if receiver not in block_vars:
                raise RuntimeError(
                    f"generated Vagrantfile uses {receiver!r} as the receiver of "
                    f"vm.provision; expected one of {sorted(block_vars)}: {stripped}"
                )
        for vm in (red, blue):
            if f'{vm["name"]}.vm' in rendered:
                raise RuntimeError(
                    f'generated Vagrantfile references {vm["name"]}.vm instead of the Ruby '
                    "block variable; Vagrant would fail with 'undefined local variable'"
                )


def main(argv: list[str] | None = None) -> int:
    """CLI: render/write the lab IaC and print the exact continuation commands."""
    logging.basicConfig(
        level=os.getenv("SOC_LOG_LEVEL", "INFO").upper(),
        format="[%(asctime)s] [%(levelname)s] [%(name)s] %(message)s",
    )
    parser = argparse.ArgumentParser(
        prog="python -m soc.iac_generator",
        description=(
            "Render the SecLoop BATTLE-FIELD Vagrantfile for one preset. "
            "Rendering does NOT start anything: run `vagrant up --provider vmware_desktop` "
            "in the generated directory afterwards."
        ),
    )
    parser.add_argument("--attack-mode", default="sqli", help="preset to render (default: sqli)")
    parser.add_argument(
        "--output-dir",
        default=None,
        help=f"parent of the env_<preset> folder (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument("--repo-root", default=None, help="repository root referenced by the file")
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="print the Vagrantfile instead of writing env_<preset>/",
    )
    parser.add_argument("--force", action="store_true", help="overwrite an existing Vagrantfile")
    args = parser.parse_args(argv)

    generator = IaCGenerator(repo_root=args.repo_root, output_dir=args.output_dir)
    try:
        if args.stdout:
            sys.stdout.write(generator.render(args.attack_mode))
            return 0
        vagrantfile = generator.generate(args.attack_mode, force=args.force)
    except (KeyError, RuntimeError, FileExistsError) as exc:
        logger.error("%s", exc)
        return 2

    env_dir = vagrantfile.parent
    sys.stdout.write(
        f"wrote {vagrantfile}\n"
        f"wrote {env_dir / 'README.md'}\n\n"
        "Next steps (generating IaC starts nothing):\n"
        f"  1. cd {env_dir.as_posix()}\n"
        "  2. vagrant up --provider vmware_desktop\n"
        f"  3. bash {(generator.repo_root / 'vagrant' / 'snapshots.sh').as_posix()}\n"
        f"  4. SOAR_VAGRANT_ROOT={env_dir.as_posix()} "
        f"python {(generator.repo_root / 'battlefield' / 'soc_server.py').as_posix()}\n"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
