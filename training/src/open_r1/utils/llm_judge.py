"""Penalty-stage judge for the SA-GRPO cascade reward (paper Eq. 21).

The fourth stage of ``sa_cascade_reward`` asks an LLM expert to rate how
*over-defensive* a generated strategy is; that rating is the penalty ``P`` that
is **subtracted** from the cascade total (``INTERFACES.md`` §10.2).

Endpoint handling (``INTERFACES.md`` §7)
---------------------------------------
The evaluation agent and the training penalty judge share one LLM endpoint
abstraction.  ``agent.llm.llm_interface`` is the single source of truth for the
endpoint configuration (``base_url`` / ``model`` / ``api_key_env`` / temperature
/ timeout) and this module is the thin adapter the training side uses.

Deliberate failure policy: when no endpoint is configured this module **raises**
instead of degrading to ``0.0``.  Degrading would silently turn the fourth reward
stage into a no-op and make a mis-configured run look like a successful one.
``INTERFACES.md`` §7.1 forbids that: "未配置端点时，必须显式报错，
不得静默返回 0.0".
"""

